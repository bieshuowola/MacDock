[CmdletBinding(DefaultParameterSetName='Dpapi')]
param(
    [Parameter(Mandatory)][string]$Setup,
    [Parameter(Mandatory,ParameterSetName='Pem')][string]$PrivateKeyPem,
    [Parameter(Mandatory,ParameterSetName='Dpapi')][string]$ProtectedKey,
    [Parameter(Mandatory)][string]$Notes,
    [switch]$AllowTestIdentity
)
$ErrorActionPreference = 'Stop'

function Get-EmbeddedUpdateMetadata([IO.Stream]$AssemblyStream) {
    $AssemblyStream.Position = 0
    $pe = [System.Reflection.PortableExecutable.PEReader]::new($AssemblyStream)
    try {
        $reader = [System.Reflection.Metadata.PEReaderExtensions]::GetMetadataReader($pe)
        $metadata = @{}
        $names = 'MacDockReleaseRepository', 'MacDockUpdatePublicKey', 'MacDockBuildSequence', 'MacDockBuildFingerprint'
        foreach ($handle in $reader.GetAssemblyDefinition().GetCustomAttributes()) {
            $attribute = $reader.GetCustomAttribute($handle)
            if ($attribute.Constructor.Kind -ne 'MemberReference') { continue }
            $constructor = $reader.GetMemberReference([System.Reflection.Metadata.MemberReferenceHandle]$attribute.Constructor)
            if ($constructor.Parent.Kind -ne 'TypeReference') { continue }
            $type = $reader.GetTypeReference([System.Reflection.Metadata.TypeReferenceHandle]$constructor.Parent)
            if ($reader.GetString($type.Namespace) -cne 'System.Reflection' -or $reader.GetString($type.Name) -cne 'AssemblyMetadataAttribute') { continue }
            $blob = $reader.GetBlobReader($attribute.Value)
            if ($blob.ReadUInt16() -ne 1) { throw 'Invalid assembly metadata attribute.' }
            $name = $blob.ReadSerializedString()
            if ($name -cin $names) { $metadata.Add($name, $blob.ReadSerializedString()) }
        }
        return $metadata
    } finally { $pe.Dispose() }
}

$setupFile = Get-Item -LiteralPath $Setup
$nameMatch = [regex]::Match($setupFile.Name, '^MacDock-(\d+(?:\.\d+){2,3})-win-x64-Setup\.exe$')
if (!$nameMatch.Success) { throw 'Unexpected setup filename.' }
$version = $nameMatch.Groups[1].Value
$directory = $setupFile.DirectoryName
$build = Get-Content -LiteralPath (Join-Path $directory 'local-build.json') -Raw | ConvertFrom-Json
$fingerprint = [Guid]::Empty
if ($build.testIdentity -isnot [bool] -or ($build.testIdentity -and !$AllowTestIdentity) -or
    $build.channelConfigured -ne $true -or $build.version -cne $version -or
    !$build.setup -or (Split-Path -Path $build.setup -Leaf) -cne $setupFile.Name -or
    $build.releaseRepository -notmatch '^[A-Za-z0-9][A-Za-z0-9-]*/[A-Za-z0-9_.-]+$' -or !$build.updatePublicKey -or
    ($build.buildSequence -isnot [long] -and $build.buildSequence -isnot [int]) -or $build.buildSequence -le 0 -or
    ![Guid]::TryParseExact($build.buildFingerprint, 'N', [ref]$fingerprint) -or $fingerprint -eq [Guid]::Empty -or
    $build.setupSha256 -notmatch '^[0-9a-f]{64}$' -or $build.payloadSha256 -notmatch '^[0-9a-f]{64}$') {
    throw 'Invalid channel build record. Use a product directory generated by Build-Product.ps1.'
}
$workspace = Split-Path $PSScriptRoot
$keyPath = (Resolve-Path -LiteralPath $(if ($ProtectedKey) { $ProtectedKey } else { $PrivateKeyPem })).Path
if ($keyPath.StartsWith($workspace + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Keep the private signing key outside the repository.'
}

$installer = [IO.File]::OpenRead($setupFile.FullName)
try {
    if ($setupFile.VersionInfo.ProductVersion.Trim() -notmatch ('^' + [regex]::Escape($version) + '(?:\.0)?$')) {
        throw 'Setup file version does not match the filename.'
    }
    $setupHash = (Get-FileHash -InputStream $installer -Algorithm SHA256).Hash.ToLowerInvariant()
    if ($setupHash -ne $build.setupSha256) { throw 'Setup SHA256 does not match the product build.' }

    $payload = [IO.File]::OpenRead((Join-Path $directory 'MacDock\MacDock.dll'))
    try {
        $payloadHash = (Get-FileHash -InputStream $payload -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($payloadHash -ne $build.payloadSha256) { throw 'MacDock.dll SHA256 does not match the product build.' }
        # Read metadata without loading the executable into the PowerShell process.
        $metadata = Get-EmbeddedUpdateMetadata $payload
    } finally { $payload.Dispose() }
    $sequenceText = $build.buildSequence.ToString([Globalization.CultureInfo]::InvariantCulture)
    if ($metadata.MacDockBuildSequence -cne $sequenceText -or $metadata.MacDockBuildFingerprint -cne $build.buildFingerprint -or
        $metadata.MacDockReleaseRepository -cne $build.releaseRepository -or $metadata.MacDockUpdatePublicKey -cne $build.updatePublicKey) {
        throw 'MacDock.dll metadata does not match the product build.'
    }

    $manifest = [ordered]@{
        Version = $version; FileName = $setupFile.Name; Size = $installer.Length; Sha256 = $setupHash
        Notes = [IO.File]::ReadAllText((Resolve-Path -LiteralPath $Notes).Path)
        BuildSequence = [long]$build.buildSequence; BuildFingerprint = $build.buildFingerprint; PayloadSha256 = $payloadHash
    }
    $bytes = [Text.Encoding]::UTF8.GetBytes(($manifest | ConvertTo-Json -Compress))
    if ($bytes.Length -gt 65536) { throw 'Update manifest exceeds size limit.' }
    $jsonPath = Join-Path $directory 'macdock-update.json'
    $sigPath = Join-Path $directory 'macdock-update.sig'
    if ((Test-Path -LiteralPath $jsonPath) -or (Test-Path -LiteralPath $sigPath)) { throw 'Output exists. Use a fresh build directory.' }

    $key = [Security.Cryptography.ECDsa]::Create()
    try {
        if ($ProtectedKey) {
            $secret = [Security.Cryptography.ProtectedData]::Unprotect([IO.File]::ReadAllBytes($keyPath), $null, [Security.Cryptography.DataProtectionScope]::CurrentUser)
            try {
                $consumed = 0
                $key.ImportPkcs8PrivateKey($secret, [ref]$consumed)
                if ($consumed -ne $secret.Length) { throw 'Invalid protected key.' }
            } finally { [Array]::Clear($secret) }
        } else { $key.ImportFromPem([IO.File]::ReadAllText($keyPath)) }
        $publicKey = [Convert]::ToBase64String($key.ExportSubjectPublicKeyInfo())
        if ($key.KeySize -ne 256 -or $key.ExportParameters($false).Curve.Oid.Value -ne '1.2.840.10045.3.1.7' -or $publicKey -cne $metadata.MacDockUpdatePublicKey) {
            throw 'The P-256 signing key does not match the public verification key embedded in MacDock.dll.'
        }
        $signature = $key.SignData($bytes, [Security.Cryptography.HashAlgorithmName]::SHA256, [Security.Cryptography.DSASignatureFormat]::IeeeP1363FixedFieldConcatenation)
    } finally { $key.Dispose() }

    $token = [Guid]::NewGuid().ToString('N')
    $tempJson = "$jsonPath.$token.tmp"
    $tempSig = "$sigPath.$token.tmp"
    $signatureMoved = $false
    try {
        [IO.File]::WriteAllBytes($tempJson, $bytes)
        [IO.File]::WriteAllBytes($tempSig, $signature)
        [IO.File]::Move($tempSig, $sigPath)
        $signatureMoved = $true
        [IO.File]::Move($tempJson, $jsonPath)
        $signatureMoved = $false
    } finally {
        if ($signatureMoved) { [IO.File]::Delete($sigPath) }
        [IO.File]::Delete($tempJson)
        [IO.File]::Delete($tempSig)
    }
    $publicKey
} finally { $installer.Dispose() }
